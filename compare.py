#!/usr/bin/env python3
"""Compare every model's answers on the labelled hosts. Reads results/answers-*.json, writes results/report.md.

Two views:
  1. The decision rule the weekly triage uses (triage.judge(): both option orders, confidence >= 0.85, a second signal).
     Only for models asked in both option orders (not Sonnet).
  2. Raw answers, rule-free: forward option order, no confidence threshold, because "confidence" means different
     things per model (a calibrated softmax for Jev and the deciders, a number Sonnet writes in text).
No API calls; standard library only.
"""
import argparse, csv, glob, json, os, statistics, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import triage  # noqa: E402

ORDER = ("jev-latest", "sonnet-claude-sonnet-5-5", "strands-decider-2B-qwen3.5-v1-2610", "strands-decider-E4B-gemma4-v1-2610")
SHORT = {"jev-latest": "Jev", "sonnet-claude-sonnet-5-5": "Sonnet",
         "strands-decider-2B-qwen3.5-v1-2610": "Strands 2B", "strands-decider-E4B-gemma4-v1-2610": "Strands E4B"}


def pct(n, d):
    return "%d/%d" % (n, d)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--labels", default="data/labelled-hosts.csv")
    ap.add_argument("--results", default="results")
    ap.add_argument("--out", default="results/report.md")
    a = ap.parse_args()

    labels = {r["hostname"].strip().lower(): r["expected"].strip() for r in csv.DictReader(open(a.labels))}
    hosts = list(labels)
    bad = [h for h in hosts if labels[h] in ("ad", "tracker")]
    good = [h for h in hosts if labels[h] == "legit"]

    files = {os.path.basename(p)[len("answers-"):-len(".json")]: p for p in glob.glob(os.path.join(a.results, "answers-*.json"))}
    names = [n for n in ORDER if n in files] + sorted(n for n in files if n not in ORDER)
    arms = [(n, SHORT.get(n, n), json.load(open(files[n]))) for n in names]
    two_orders = [(n, s, f) for n, s, f in arms if all("category_rev" in f["hosts"][h] for h in hosts)]

    L = []
    w = L.append
    w("# Decision models on %d labelled DNS hostnames\n" % len(hosts))
    w("Generated by `compare.py` from `results/answers-*.json`. Labels: `%s` (%d ad, %d tracker, %d legit).\n" % (
        a.labels, sum(v == "ad" for v in labels.values()), sum(v == "tracker" for v in labels.values()), len(good)))
    for n, s, f in arms:
        w("- **%s** (`%s`): %s." % (s, n, f.get("source", "")))
    w("")

    # 1. The weekly rule.
    w("## 1. With the weekly triage's decision rule\n")
    w("`triage.judge()`: block only when both option orders give the same block category (advertising, tracking or "
      "malicious) with confidence >= %.2f and the ad-tech or unwanted question agrees; otherwise review or quiet. "
      "Sonnet was asked in one order only, so it has no column here.\n" % triage.MIN_CONF)
    v = {n: {h: triage.judge(h, f["hosts"][h])[0] for h in hosts} for n, _, f in two_orders}
    rows = [
        ("**Legit hosts proposed for block**", lambda n, f: pct(sum(v[n][h] == "block" for h in good), len(good))),
        ("Legit hosts sent to review", lambda n, f: pct(sum(v[n][h] == "review" for h in good), len(good))),
        ("Ad/tracker hosts proposed for block", lambda n, f: pct(sum(v[n][h] == "block" for h in bad), len(bad))),
        ("Ad/tracker hosts flagged (block or review)", lambda n, f: pct(sum(v[n][h] != "quiet" for h in bad), len(bad))),
        ("Ad/tracker hosts missed (quiet)", lambda n, f: pct(sum(v[n][h] == "quiet" for h in bad), len(bad))),
        ("Category changed when option order reversed", lambda n, f: pct(sum(f["hosts"][h]["category"] != f["hosts"][h]["category_rev"] for h in hosts), len(hosts))),
        ("Category confidence, median (lower of both orders)", lambda n, f: "%.2f" % statistics.median(min(f["hosts"][h]["cat_conf"], f["hosts"][h]["cat_conf_rev"]) for h in hosts)),
        ("Hosts at or above %.2f confidence" % triage.MIN_CONF, lambda n, f: pct(sum(min(f["hosts"][h]["cat_conf"], f["hosts"][h]["cat_conf_rev"]) >= triage.MIN_CONF for h in hosts), len(hosts))),
    ]
    w("| metric | " + " | ".join(s for _, s, _ in two_orders) + " |")
    w("|---|" + "---|" * len(two_orders))
    for title, fn in rows:
        w("| %s | %s |" % (title, " | ".join(fn(n, f) for n, _, f in two_orders)))
    for n, s, _ in two_orders:
        missed = [h for h in bad if v[n][h] == "quiet"]
        if missed:
            w("\n%s missed: %s" % (s, ", ".join(missed)))
    w("")

    # 2. Rule-free.
    w("## 2. Raw answers, no decision rule\n")
    w("Forward option order, no confidence threshold. Each cell: *ad/tracker hosts caught (of %d) · legit hosts caught (of %d)*; "
      "the first number should be high, the second 0. The cut-offs 0.5 and 2.5 are the weekly rule's, not tuned for any model.\n" % (len(bad), len(good)))
    num = lambda x: float(x) if x is not None else 0.0
    tests = [
        ("Category is advertising, tracking or malicious", lambda r: r.get("category") in triage.BLOCK),
        ("P(ad-tech) >= 0.5", lambda r: num(r.get("p_adtech")) >= 0.5),
        ("Unwanted score >= 2.5 (0-4 scale)", lambda r: num(r.get("unwanted")) >= 2.5),
    ]
    w("| test | " + " | ".join(s for _, s, _ in arms) + " |")
    w("|---|" + "---|" * len(arms))
    for title, t in tests:
        w("| %s | %s |" % (title, " | ".join("%d · %d" % (sum(t(f["hosts"][h]) for h in bad), sum(t(f["hosts"][h]) for h in good))
                                              for _, _, f in arms)))
    w("")

    # 3. Speed and cost.
    w("## 3. Speed and cost\n")
    w("| model | time per host, median (Sonnet: 1 request per host; the others: 2) | tokens per host |")
    w("|---|---|---|")
    for n, s, f in arms:
        ms = [r["ms"] for r in f["hosts"].values() if "ms" in r]
        tok = [r["in_tokens"] + r["out_tokens"] for r in f["hosts"].values() if "in_tokens" in r]
        where = f.get("device", "over the network")
        w("| %s | %s | %s |" % (s, "%d ms, %s (%d hosts timed)" % (statistics.median(ms), where, len(ms)) if ms else "not recorded",
                                "%d (billed)" % statistics.median(tok) if tok and "decider" not in n else ("%d (local, no charge)" % statistics.median(tok) if tok else "not recorded")))
    w("\nNetwork and on-device times are not comparable with each other; the two deciders ran on the same Mac and are.\n")

    # 4. Per host.
    w("## 4. Every answer, forward option order\n")
    w("Each cell: category · P(ad-tech) · unwanted (0-4).\n")
    w("| host | label | " + " | ".join(s for _, s, _ in arms) + " |")
    w("|---|---|" + "---|" * len(arms))
    f2 = lambda x: "%.2f" % float(x) if x is not None else "?"
    f1 = lambda x: "%.1f" % float(x) if x is not None else "?"
    for h in hosts:
        w("| %s | %s | %s |" % (h, labels[h], " | ".join("%s · %s · %s" % (f["hosts"][h].get("category"), f2(f["hosts"][h].get("p_adtech")),
                                                                           f1(f["hosts"][h].get("unwanted"))) for _, _, f in arms)))

    open(a.out, "w").write("\n".join(L) + "\n")
    print(a.out)


if __name__ == "__main__":
    main()
